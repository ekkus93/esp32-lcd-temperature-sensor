import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';

// Ajv builds its checking code with `new Function` when a schema is compiled in the browser, which
// the device's Content-Security-Policy (script-src 'self') forbids. The validators are therefore
// compiled here, at build time, into plain ES module code that the page imports.
const standaloneCode = standalone;
const root = fileURLToPath(new URL('../..', import.meta.url));
const formatter = path.join(root, 'web/node_modules/.bin/prettier');
const output = path.join(root, 'web/src/api/schema-validators.generated.ts');

// [export name, schema file, exported type, module that declares the type]
const validators = [
  ['alerts', 'alerts.schema.json', 'Alerts', 'api-alerts.generated'],
  ['authState', 'auth-state.schema.json', 'AuthState', 'api-auth.generated'],
  ['clockDiagnostics', 'clock-diagnostics.schema.json', 'ClockDiagnostics', 'api-clock-diagnostics.generated'],
  ['deviceSettings', 'device-settings.schema.json', 'DeviceSettings', 'api-device-settings.generated'],
  ['deviceSettingsPatch', 'device-settings-patch.schema.json', 'DeviceSettingsPatch', 'api-device-settings-patch.generated'],
  ['devicePublicSettings', 'device-settings-public.schema.json', 'PublicDeviceSettings', 'api-device-settings-public.generated'],
  ['history', 'history.schema.json', 'HistoryResult', 'api-history.generated'],
  ['probeScan', 'probe-scan.schema.json', 'ProbeScanStatus', 'api-probe-scan.generated'],
  ['sensorConfigurations', 'sensor-configurations.schema.json', 'SensorConfigurations', 'api-sensors.generated'],
  ['sensorPatch', 'sensor-patch.schema.json', 'SensorPatch', 'api-sensor-patch.generated'],
  ['sensorRetire', 'sensor-retire.schema.json', 'SensorRetirementAcceptance', 'api-sensor-retire.generated'],
  ['sensorStorage', 'sensor-storage.schema.json', 'SensorStorageStatus', 'api-sensor-storage.generated'],
  ['snapshot', 'snapshot.schema.json', 'Snapshot', 'generated'],
  ['systemFactoryReset', 'system-factory-reset.schema.json', 'SystemFactoryResetAcceptance', 'api-system-factory-reset.generated'],
  ['systemReboot', 'system-reboot.schema.json', 'SystemRebootAcceptance', 'api-system-reboot.generated'],
  ['wifiScan', 'wifi-scan.schema.json', 'WifiScan', 'api-wifi-scan.generated'],
  ['wifiStatus', 'wifi-status.schema.json', 'WifiStatus', 'api-wifi-status.generated'],
];

const ajv = new Ajv({ code: { source: true, esm: true } });
const refs = {};
for (const [name, file] of validators) {
  const schema = JSON.parse(readFileSync(path.join(root, 'contracts', file), 'utf8'));
  ajv.addSchema(schema, name);
  refs[name] = name;
}
// Ajv's standalone output still loads its string-length helper with CommonJS `require()`, even with
// `esm: true`. The production bundler converts that, but the Vite dev server does not, and a raw
// `require` leaves a blank page in development. Replace it with the same count (Unicode code points,
// a surrogate pair counting once, as Ajv's ucs2length does), and refuse any other `require`.
const code = standaloneCode(ajv, refs).replace(
  /const (func\d+) = require\(["']ajv\/dist\/runtime\/ucs2length["']\)\.default;/g,
  'const $1 = (value) => Array.from(value).length;',
);
if (/\brequire\(/.test(code))
  throw new Error('Generated validators still contain require(); they must be plain ES modules');

const types = [...new Map(validators.map(([, , type, module]) => [type, module])).entries()];
const header = [
  '// @ts-nocheck',
  '/* eslint-disable */',
  '// Generated by web/scripts/generate-validators.mjs from contracts/*.schema.json. Do not edit.',
  '',
  ...types.map(([type, module]) => `import type { ${type} } from './${module}';`),
  '',
].join('\n');
const typed = validators
  .map(
    ([name, , type]) =>
      `export const ${name}Valid = ${name} as (value: unknown) => value is ${type};`,
  )
  .join('\n');
writeFileSync(output, `${header}${code}\n\n${typed}\n`);
execFileSync(formatter, ['--write', output], { stdio: 'inherit' });
