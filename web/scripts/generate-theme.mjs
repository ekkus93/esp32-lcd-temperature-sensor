// Writes src/theme/tokens.generated.ts from the seed colour in src/theme/tokenSource.ts.
// Run with `npm run theme:generate` after changing the seed or the status or series sources;
// src/theme/tokens.test.ts fails while the committed file is out of date.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildTokens } from '../src/theme/tokenSource.ts';

const target = fileURLToPath(new URL('../src/theme/tokens.generated.ts', import.meta.url));
const body = JSON.stringify(buildTokens(), null, 2);
writeFileSync(
  target,
  `// Generated by scripts/generate-theme.mjs from src/theme/tokenSource.ts. Do not edit.
import type { Tokens } from './tokenSource';

export const tokens: Tokens = ${body};
`,
);
console.log(`Wrote ${target}`);
