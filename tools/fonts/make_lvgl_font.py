#!/usr/bin/env python3
"""Turn a TrueType font into an LVGL 9 bitmap font (4 bits per pixel, uncompressed) as a C file.

A small stand-in for lv_font_conv, using the FreeType rasterizer inside Pillow, so fonts can be
regenerated offline:  python3 tools/fonts/make_lvgl_font.py FONT.ttf SIZE NAME OUT.c [--notice FILE]

Only the characters in RANGES are included (basic Latin and the degree sign by default), which keeps
a font to a few kilobytes. There is no kerning table.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

RANGES = [(0x20, 0x7E), (0xB0, 0xB0)]


def codepoints():
    return [cp for lo, hi in RANGES for cp in range(lo, hi + 1)]


def render(font, character):
    """Return (box_w, box_h, ofs_x, ofs_y, advance_px, 4-bit pixel rows) for one character."""
    advance = font.getlength(character)
    if character == ' ':
        return 0, 0, 0, 0, advance, []
    left, top, right, bottom = font.getbbox(character, anchor='ls')
    width, height = right - left, bottom - top
    if width <= 0 or height <= 0:
        return 0, 0, 0, 0, advance, []
    canvas = Image.new('L', (width + 4, height + 4), 0)
    ImageDraw.Draw(canvas).text((2 - left, 2 - top), character, font=font, fill=255, anchor='ls')
    # Tight crop (anti-aliasing can leave a faint edge row, which is kept if it is visible).
    box = canvas.getbbox()
    if box is None:
        return 0, 0, 0, 0, advance, []
    cropped = canvas.crop(box)
    w, h = cropped.size
    ofs_x = box[0] - 2 + left
    ofs_y = -(box[3] - 2 + top)  # distance of the box bottom above the baseline
    pixels = [[min(15, (cropped.getpixel((x, y)) + 8) >> 4) for x in range(w)] for y in range(h)]
    return w, h, ofs_x, ofs_y, advance, pixels


def pack(pixels):
    flat = [v for row in pixels for v in row]
    if len(flat) % 2:
        flat.append(0)
    return bytes((flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2))


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('font')
    parser.add_argument('size', type=int)
    parser.add_argument('name', help='C identifier, e.g. font_charter_14')
    parser.add_argument('output', type=Path)
    parser.add_argument('--notice', type=Path, help='licence notice to put in the file header')
    args = parser.parse_args()
    font = ImageFont.truetype(args.font, args.size)
    ascent, descent = font.getmetrics()
    cap = font.getbbox('H', anchor='ls')
    xh = font.getbbox('x', anchor='ls')
    bitmap = bytearray()
    glyphs = [(0, 0, 0, 0, 0, 0)]  # id 0 is reserved
    for cp in codepoints():
        w, h, ox, oy, adv, pixels = render(font, chr(cp))
        index = len(bitmap)
        bitmap += pack(pixels)
        glyphs.append((index, int(round(adv * 16)), w, h, ox, oy))
    notice = ''
    if args.notice:
        notice = ''.join(' * ' + line.rstrip() + '\n' for line in args.notice.read_text().splitlines())
    lines = [
        '/*******************************************************************************',
        f' * Size: {args.size} px, Bpp: 4, no compression, no kerning',
        f' * Generated by tools/fonts/make_lvgl_font.py from {Path(args.font).name}',
        ' * Characters: U+0020 to U+007E and U+00B0 (degree sign)',
    ]
    if notice:
        lines += [' *', notice.rstrip('\n')]
    lines += [' ******************************************************************************/', '',
              '#include "lvgl.h"', '',
              f'static const uint8_t {args.name}_bitmap[] = {{']
    for i in range(0, len(bitmap), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in bitmap[i:i + 16]) + ',')
    if not bitmap:
        lines.append('    0x00,')
    lines += ['};', '', f'static const lv_font_fmt_txt_glyph_dsc_t {args.name}_glyphs[] = {{']
    for g in glyphs:
        lines.append('    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d},' % g)
    lines += ['};', '',
              f'static const lv_font_fmt_txt_cmap_t {args.name}_cmaps[] = {{',
              '    {.range_start = 32, .range_length = 95, .glyph_id_start = 1, .unicode_list = NULL,',
              '     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},',
              '    {.range_start = 176, .range_length = 1, .glyph_id_start = 96, .unicode_list = NULL,',
              '     .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},',
              '};', '',
              f'static const lv_font_fmt_txt_dsc_t {args.name}_dsc = {{',
              f'    .glyph_bitmap = {args.name}_bitmap, .glyph_dsc = {args.name}_glyphs,',
              f'    .cmaps = {args.name}_cmaps, .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 2,',
              '    .bpp = 4, .kern_classes = 0, .bitmap_format = 0,', '};', '',
              f'const lv_font_t {args.name} = {{',
              '    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,',
              '    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,',
              f'    .line_height = {ascent + descent}, .base_line = {descent},',
              f'    .cap_height = {-cap[1]}, .x_height = {-xh[1]},',
              '    .subpx = LV_FONT_SUBPX_NONE, .underline_position = -1, .underline_thickness = 1,',
              f'    .static_bitmap = 1, .dsc = &{args.name}_dsc, .fallback = NULL, .user_data = NULL,',
              '};', '']
    args.output.write_text('\n'.join(lines))
    print(f'{args.output.name}: {len(bitmap)} bytes of bitmap, {len(glyphs)} glyphs, line height {ascent + descent}')


if __name__ == '__main__':
    main()
